mod tests {
    use super::to_smt_bool;

    #[test]
    fn translates_abs_postcondition() {
        assert_eq!(
            to_smt_bool("result == x || result == -x").unwrap(),
            "(or (= result x) (= result (- x)))"
        );
    }
}
